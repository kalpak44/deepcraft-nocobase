#!/usr/bin/env python3
"""Point the meeting-transcription workflow back at this box's own whisper.

Runs *on the box*, against the app on loopback, and reads the root credentials
out of the application's own .env — same shape as register-docs-employee.py, so
nothing carries a password over the wire.

Why this exists
---------------
The workflow "Meetings: Transcribe Recording" is runtime state: it lives in the
database, not in the playbook, so a restore or a hand-edit can silently undo it
and CI will never notice. Two regressions had already happened by the time this
was written, and both failed the same way — the transcript simply never
appeared, with the error buried in the execution log:

1. Both the audio URL and the API URL hardcoded `nocobase.pavel-usanli.online`,
   the box's previous public name. Once that DNS went away every run died with
   `getaddrinfo ENOTFOUND`. Last success 2026-08-31.

2. Independently, the attachment URL *shape* changed. The runs that worked
   fetched `/storage/uploads/<filename>`, which the app serves statically and
   unauthenticated. `recording[0].url` now yields `/files/main/main/attachments/
   <id>.<ext>` — the file-manager route, which answers 403 "No permissions" to
   an anonymous fetch. The transcribe plugin fetches `audioUrl` with a bare
   `fetch()` and sends no token, so that route can never work for it.

So the fix is not just the hostname: the script node has to build the static
path from the filename itself.

Everything addresses the app over loopback. That is not only faster — it keeps
transcription off the Cloudflare tunnel entirely, so it does not depend on
public DNS, does not meet the 100 MB tunnel cap, and cannot break again the next
time the public hostname changes.

Idempotent: it compares the live config against what it wants and exits without
touching anything when they already agree. Run it as often as you like.

NocoBase refuses to reconfigure nodes of a workflow version that has executed
("Nodes in executed workflow could not be reconfigured"), so applying a change
means taking a revision — a new version in the same `key` chain — editing that,
and enabling it. `WorkflowRepository.revision` copies each node with its `key`
preserved, which is what keeps the `{{$jobsMapByNodeKey.*}}` references between
nodes valid across the copy.

Usage:
    configure-transcription-workflow.py

Environment:
    TRANSCRIPTION_WORKFLOW_KEY  workflow key, default "4mafzanono2"
    TRANSCRIPTION_BASE_URL      default http://127.0.0.1:13000
    TRANSCRIPTION_TIMEOUT_MS    request node timeout, default 1800000 (30 min)
    NOCOBASE_APP_ENV            path to the app .env, default /data/nocobase/app/.env
    NOCOBASE_API                default http://127.0.0.1:13000/api/
"""

import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request

API = os.environ.get('NOCOBASE_API', 'http://127.0.0.1:13000/api/')
APP_ENV = os.environ.get('NOCOBASE_APP_ENV', '/data/nocobase/app/.env')

KEY = os.environ.get('TRANSCRIPTION_WORKFLOW_KEY', '4mafzanono2')
BASE = os.environ.get('TRANSCRIPTION_BASE_URL', 'http://127.0.0.1:13000').rstrip('/')

# whisper on this box decodes at roughly eight times slower than realtime — one
# thread, CPUWeight 20, two shared cores — measured at 91s for an 11s clip. The
# node's original 60s meant anything over about seven seconds of audio timed
# out, which would have broken transcription even after the hostnames were
# fixed. 30 minutes covers a ~4 minute recording with room to spare.
TIMEOUT_MS = int(os.environ.get('TRANSCRIPTION_TIMEOUT_MS', '1800000'))

# Titles, not ids: ids are regenerated by every revision, titles are what a
# person sees in the workflow canvas and are stable across versions.
AUDIO_NODE_TITLE = 'Build audio URL'
REQUEST_NODE_TITLE = 'Call transcription API'

# encodeURIComponent, not a bare concat: real uploads are named things like
# "Recording (4)-msher8.m4a", and the spaces and parentheses have to survive the
# trip or the static handler answers 404.
DESIRED_SCRIPT = (
    'return "%s/storage/uploads/" + encodeURIComponent(recording[0].filename);' % BASE
)
DESIRED_URL = '%s/api/transcription:transcribe' % BASE


def app_env(path):
    """Parse the application's .env without a shell.

    Deliberately not `source`d: the values are raw and unquoted, and the root
    password on this installation contains characters a shell would mangle or
    execute.
    """
    out = {}
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith('#') and '=' in line:
                key, value = line.split('=', 1)
                out[key.strip()] = value.strip()
    return out


class Api:
    def __init__(self, token=None):
        self.token = token

    def __call__(self, path, body=None, method=None):
        req = urllib.request.Request(
            API + path, method=method or ('POST' if body is not None else 'GET')
        )
        req.add_header('Content-Type', 'application/json')
        # See .claude/rules/nocobase.md — without this, anything that resolves
        # date variables dies with a bare "m.startOf is not a function".
        req.add_header('X-Timezone', '+00:00')
        if self.token:
            req.add_header('Authorization', 'Bearer ' + self.token)
        data = json.dumps(body).encode() if body is not None else None
        try:
            with urllib.request.urlopen(req, data, timeout=120) as resp:
                raw = resp.read()
                return json.loads(raw) if raw else {}
        except urllib.error.HTTPError as err:
            detail = err.read().decode('utf-8', 'replace')[:400]
            raise SystemExit(f'{method or "GET"} {path} failed: {err.code} {detail}')
        except urllib.error.URLError as err:
            raise SystemExit(f'{path} unreachable: {err.reason} — is nocobase.service running?')


def q(obj):
    return urllib.parse.quote(json.dumps(obj))


def versions(api):
    """Every version in this workflow's key chain, newest first.

    Ordered by id, not by a `version` field: the workflows table has no such
    column — NocoBase renders "v3" from the row's ordinal position in the key
    chain — so reading one back gives None for every row and sorts nothing.
    Ids are snowflakes and monotonic, which is the ordering the UI is showing.
    """
    rows = api(f'workflows:list?pageSize=50&appends[]=nodes&filter={q({"key": KEY})}').get('data', [])
    return sorted(rows, key=lambda w: int(w['id']), reverse=True)


def node_by_title(workflow, title):
    for node in workflow.get('nodes') or []:
        if node.get('title') == title:
            return node
    raise SystemExit(
        f'workflow {KEY} id={workflow.get("id")} has no node titled "{title}" — '
        'it has been restructured, so fix it by hand rather than letting this '
        'script guess which node to rewrite'
    )


def converged(workflow):
    """True when this version already says what we want it to say."""
    audio = node_by_title(workflow, AUDIO_NODE_TITLE)
    request = node_by_title(workflow, REQUEST_NODE_TITLE)
    return (
        (audio.get('config') or {}).get('content') == DESIRED_SCRIPT
        and (request.get('config') or {}).get('url') == DESIRED_URL
        and (request.get('config') or {}).get('timeout') == TIMEOUT_MS
    )


def main():
    env = app_env(APP_ENV)
    api = Api()
    api.token = api('auth:signIn', {
        'email': env['INIT_ROOT_EMAIL'], 'password': env['INIT_ROOT_PASSWORD']
    })['data']['token']

    chain = versions(api)
    if not chain:
        raise SystemExit(f'no workflow with key {KEY} — nothing to configure')

    live = next((w for w in chain if w.get('enabled')), None)
    if live is None:
        raise SystemExit(
            f'no enabled version of workflow {KEY}. Enable one in the UI first — '
            'this script repairs the live version, it does not choose one'
        )

    print(f'workflow "{live.get("title")}" key={KEY} live id={live["id"]}')

    if converged(live):
        print('  already points at ' + BASE + f' with a {TIMEOUT_MS}ms timeout — nothing to do')
        return

    audio = node_by_title(live, AUDIO_NODE_TITLE)
    request = node_by_title(live, REQUEST_NODE_TITLE)
    print(f'  {AUDIO_NODE_TITLE}: {(audio.get("config") or {}).get("content")!r}')
    print(f'  {REQUEST_NODE_TITLE}: {(request.get("config") or {}).get("url")!r} '
          f'timeout={(request.get("config") or {}).get("timeout")}')

    # A version that has run cannot be reconfigured, so branch a new one. The
    # filter carries the key, which is what makes this a new *version* rather
    # than a detached "... copy" workflow with a key of its own.
    revised = api(
        f'workflows:revision?filterByTk={live["id"]}&filter={q({"key": KEY})}', {}
    )['data']
    print(f'  took revision -> new version, id {revised.get("id")}')

    fresh = next((w for w in versions(api) if w['id'] == revised['id']), None)
    if fresh is None:
        raise SystemExit('the revision did not come back in the version list')

    new_audio = node_by_title(fresh, AUDIO_NODE_TITLE)
    new_request = node_by_title(fresh, REQUEST_NODE_TITLE)

    audio_config = dict(new_audio.get('config') or {})
    audio_config['content'] = DESIRED_SCRIPT
    api(f'flow_nodes:update?filterByTk={new_audio["id"]}',
        {'config': audio_config}, method='POST')
    print(f'  {AUDIO_NODE_TITLE} -> builds {BASE}/storage/uploads/<filename>')

    request_config = dict(new_request.get('config') or {})
    request_config['url'] = DESIRED_URL
    request_config['timeout'] = TIMEOUT_MS
    api(f'flow_nodes:update?filterByTk={new_request["id"]}',
        {'config': request_config}, method='POST')
    print(f'  {REQUEST_NODE_TITLE} -> {DESIRED_URL}, timeout {TIMEOUT_MS}ms')

    api(f'workflows:update?filterByTk={fresh["id"]}', {'enabled': True})
    print(f'  enabled id {fresh["id"]}')

    # Verify against the server rather than trusting the writes: enabling a
    # version is what demotes the previous one, and a chain with two enabled
    # versions would transcribe every recording twice.
    after = versions(api)
    enabled = [w for w in after if w.get('enabled')]
    if len(enabled) != 1 or enabled[0]['id'] != fresh['id']:
        raise SystemExit(
            'expected exactly the new version to be enabled, got: '
            + ', '.join(f'{w["id"]}(enabled={w.get("enabled")})' for w in after)
        )
    if not converged(enabled[0]):
        raise SystemExit('the new version did not come back with the config that was just written')
    print(f'verified: id {enabled[0]["id"]} is the only enabled version and reads as intended')


if __name__ == '__main__':
    sys.exit(main())
